-- Short, human-friendly order numbers ("R355"). A sequence is safe under concurrent checkouts
-- from several terminals; gaps after rolled-back transactions are acceptable.
CREATE SEQUENCE sale_order_number_seq;

CREATE TABLE sale_order (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_number      BIGINT         NOT NULL,
    receipt_code      VARCHAR(16)    NOT NULL,
    -- Generated by the client per checkout attempt; makes retries and double-taps idempotent.
    client_request_id UUID           NOT NULL,
    status            VARCHAR(10)    NOT NULL,
    note              VARCHAR(500),
    total             NUMERIC(12, 2) NOT NULL,
    staff_id          BIGINT         NOT NULL REFERENCES staff (id),
    created_at        TIMESTAMPTZ    NOT NULL,
    CONSTRAINT sale_order_number_uq UNIQUE (order_number),
    CONSTRAINT sale_order_receipt_code_uq UNIQUE (receipt_code),
    CONSTRAINT sale_order_client_request_uq UNIQUE (client_request_id),
    CONSTRAINT sale_order_status_ck CHECK (status IN ('OPEN', 'CLOSED', 'VOIDED')),
    CONSTRAINT sale_order_total_ck CHECK (total >= 0)
);

-- Lines snapshot the item's name and price at the time of sale, so later catalogue
-- changes never rewrite history or reports.
CREATE TABLE sale_order_line (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id    BIGINT         NOT NULL REFERENCES sale_order (id),
    line_number SMALLINT       NOT NULL,
    item_id     BIGINT         NOT NULL REFERENCES item (id),
    item_name   VARCHAR(120)   NOT NULL,
    unit_price  NUMERIC(10, 2) NOT NULL,
    quantity    INT            NOT NULL,
    line_total  NUMERIC(12, 2) NOT NULL,
    -- Also serves "lines of an order" lookups.
    CONSTRAINT sale_order_line_number_uq UNIQUE (order_id, line_number),
    CONSTRAINT sale_order_line_unit_price_ck CHECK (unit_price >= 0),
    CONSTRAINT sale_order_line_quantity_ck CHECK (quantity > 0),
    CONSTRAINT sale_order_line_total_ck CHECK (line_total = unit_price * quantity)
);

CREATE TABLE payment (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id          BIGINT         NOT NULL REFERENCES sale_order (id),
    payment_method_id BIGINT         NOT NULL REFERENCES payment_method (id),
    amount            NUMERIC(12, 2) NOT NULL,
    -- e.g. card approval / transaction reference from the terminal
    reference         VARCHAR(60),
    staff_id          BIGINT         NOT NULL REFERENCES staff (id),
    created_at        TIMESTAMPTZ    NOT NULL,
    CONSTRAINT payment_amount_ck CHECK (amount > 0)
);

CREATE INDEX payment_order_idx ON payment (order_id);
